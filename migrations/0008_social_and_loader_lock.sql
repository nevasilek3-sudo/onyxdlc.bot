ALTER TABLE users ADD COLUMN IF NOT EXISTS loader_locked BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS social_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    prefix TEXT NOT NULL DEFAULT '',
    muted_until TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS social_audit (
    id BIGSERIAL PRIMARY KEY,
    actor BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    target BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
